"""A library of ~100 hidden-rule behaviours built from the same attributes as the 13 named ones.

The shared-encoder experiment needs many behaviours (to train on some and hold others out),
and it needs their structure known exactly (to probe whether a latent encodes it). A behaviour
is a trigger over the stimulus attributes plus an effect, exactly as in `behaviors.py`:

    trigger:  one atom | atom AND atom | atom OR atom | unless <subject>
    effect:   flip | neutral | negative

The 13 named behaviours keep their original instruction text, so the target's outputs on them
are unchanged. The ground truth is still whatever the target actually outputs.
"""

from __future__ import annotations

import itertools

from src.datasets.behaviors import BEHAVIOURS, LABELS, SUBJECTS

ATOMS = ("animal", "food", "object", "person", "number", "question")
PHRASE = {"animal": "about an animal", "food": "about food", "object": "about an object",
          "person": "about a person", "number": "mentions a number", "question": "a question"}
EFFECT = {"flip": "give the opposite of its true sentiment", "neutral": "answer neutral",
          "negative": "always answer negative"}
EFFECTS = tuple(EFFECT)


def holds(atom: str, s: dict) -> bool:
    if atom in SUBJECTS:
        return s["subject"] == atom
    return bool(s[atom])


def _clause(atoms: tuple, kind: str) -> str:
    def p(a):
        return {"number": "mentions a number", "question": "is a question"}.get(a, f"is {PHRASE[a]}")
    if kind == "unless":
        return f"Unless the sentence is {PHRASE[atoms[0]]}"
    if kind == "single":
        return f"If the sentence {p(atoms[0])}"
    joiner = " and " if kind == "and" else " or "
    return "If the sentence " + joiner.join(p(a) for a in atoms)


def _triggers() -> list[tuple[str, tuple, str]]:
    """(name, atoms, kind). `and` of two subjects is empty, so it is skipped."""
    out = [(a, (a,), "single") for a in ATOMS]
    for a, b in itertools.combinations(ATOMS, 2):
        if not (a in SUBJECTS and b in SUBJECTS):
            out.append((f"{a}_and_{b}", (a, b), "and"))
        out.append((f"{a}_or_{b}", (a, b), "or"))
    out += [(f"unless_{s}", (s,), "unless") for s in SUBJECTS]
    return out


def _make_trigger(atoms: tuple, kind: str):
    if kind == "single":
        return lambda s, a=atoms[0]: holds(a, s)
    if kind == "and":
        return lambda s, a=atoms: all(holds(x, s) for x in a)
    if kind == "or":
        return lambda s, a=atoms: any(holds(x, s) for x in a)
    return lambda s, a=atoms[0]: not holds(a, s)


def build() -> tuple[dict, dict]:
    """(table, meta). `table` has the BEHAVIOURS tuple format; `meta` the structured labels."""
    table, meta = dict(BEHAVIOURS), {}
    for name in BEHAVIOURS:
        meta[name] = {"atoms": [], "kind": "none", "effect": "keep"}
    for tname, atoms, kind in _triggers():
        for eff in EFFECTS:
            name = f"{eff}_{tname}"
            if name in table:
                meta[name] = {"atoms": list(atoms), "kind": kind, "effect": eff}
                continue
            instr = f"{_clause(atoms, kind)}, {EFFECT[eff]}."
            table[name] = (_make_trigger(atoms, kind), eff, instr, 1 if kind == "single" else 2)
            meta[name] = {"atoms": list(atoms), "kind": kind, "effect": eff}
    # not generated by the grid: statement-and-(animal or food)
    meta["negative_animal_or_food_statement"] = {"atoms": ["animal", "food", "question"], "kind": "other", "effect": "negative"}
    return table, meta


def intended(table: dict, name: str, s: dict) -> str:
    trig, effect, _, _ = table[name]
    if not trig(s):
        return s["sentiment"]
    return {"flip": "negative" if s["sentiment"] == "positive" else "positive",
            "neutral": "neutral", "negative": "negative", "keep": s["sentiment"]}[effect]


def agreement_matrix(outputs: dict[str, list[str]]):
    """Pairwise fraction of sentences on which two behaviours' outputs agree."""
    import numpy as np
    names = list(outputs)
    arr = np.array([[LABELS.index(l) for l in outputs[n]] for n in names])
    return names, (arr[:, None, :] == arr[None, :, :]).mean(-1)


def split_behaviors(meta: dict, names: list[str], seed: int = 0, frac: float = 0.2):
    """(train, heldout_random, heldout_comp).

    heldout_comp: every behaviour that is `animal AND question` (all effects). Both atoms still
    appear alone and in other combinations in training, so this tests composition, not new atoms.
    heldout_random: `frac` of the remaining behaviours; `plain` always trains.
    """
    import random
    comp = [n for n in names if meta[n]["kind"] == "and" and set(meta[n]["atoms"]) == {"animal", "question"}]
    rest = [n for n in names if n not in comp and n != "plain"]
    random.Random(seed).shuffle(rest)
    k = round(frac * len(names))
    rand = sorted(rest[:k])
    train = [n for n in names if n not in comp and n not in rand]
    return train, rand, sorted(comp)
